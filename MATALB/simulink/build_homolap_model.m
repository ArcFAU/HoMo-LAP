function mdl = build_homolap_model(saveDir)
%BUILD_HOMOLAP_MODEL  Build simulink\HoMoLapVehicle.slx: the HoMo-LAP car and AI driver in Simulink.
%   build_homolap_model() creates the model from scratch (it is generated, so this script is the
%   source; rerun it after changing the blocks). The blocks call the same functions as the MATLAB
%   game, so the game, the headless AI lap and the Simulink model share one physics source:
%     Driver (AI)          hotlap.aiDriver: path follower plus the speed plan, every 4 steps (150 Hz)
%     Vehicle dynamics     hotlap.physicsStep: single-track model at 600 Hz; hotlap.nearestPoint
%                          gives lap distance and lateral offset every 4 steps
%     Lap timing           lap counter and lap times at the start/finish line
%   Signals go to the workspace (simOut) and to the scopes. Parameters come from the struct HL in
%   the model workspace (homolapModelParams); run_simulink_lap sets them for any setup.
%   Needs Simulink; MATLAB Function blocks are compiled with the C compiler that ships with MATLAB.
if nargin < 1, saveDir = fileparts(mfilename('fullpath')); end
mdl = 'HoMoLapVehicle';
if bdIsLoaded(mdl), close_system(mdl, 0); end
f = fullfile(saveDir, [mdl '.slx']);
if exist(f, 'file'), movefile(f, [f '.bak'], 'f'); end   % keep the previous build
new_system(mdl);
set_param(mdl, 'Solver', 'FixedStepDiscrete', 'FixedStep', '1/600', 'StopTime', '165', 'SolverMode', 'SingleTasking', ...
    'ReturnWorkspaceOutputs', 'on', 'SignalLogging', 'on', 'SaveFormat', 'Dataset');
set_param(mdl, 'Description', 'HoMo-LAP: FAUmax tau single-track model with the AI driver on the FSG endurance track (generated by build_homolap_model.m).');

% blocks
fb = 'simulink/User-Defined Functions/MATLAB Function';
add_block(fb, [mdl '/Driver (AI)'], 'Position', [260 100 400 180]);
add_block(fb, [mdl '/Vehicle dynamics'], 'Position', [560 90 720 210]);
add_block(fb, [mdl '/Lap timing'], 'Position', [880 300 1020 380]);
add_block('simulink/Signal Attributes/Rate Transition', [mdl '/RT in'], 'Position', [170 125 200 155], 'OutPortSampleTime', '4/600');
add_block('simulink/Signal Attributes/Rate Transition', [mdl '/RT out'], 'Position', [460 125 490 155], 'OutPortSampleTime', '1/600');
add_block('simulink/Discrete/Unit Delay', [mdl '/State feedback'], 'Position', [560 260 600 300], 'InitialCondition', 'zeros(10,1)', 'SampleTime', '1/600');
add_block('simulink/Signal Routing/Demux', [mdl '/Demux'], 'Position', [800 80 805 240], 'Outputs', '10');
add_block('simulink/Math Operations/Gain', [mdl '/To km per h'], 'Position', [880 150 930 180], 'Gain', '3.6');
add_block('simulink/Sinks/Scope', [mdl '/Speed km_h'], 'Position', [980 145 1010 185]);
add_block('simulink/Sinks/XY Graph', [mdl '/Driven line'], 'Position', [980 60 1010 100]);
add_block('simulink/Sinks/Scope', [mdl '/Forces'], 'Position', [980 210 1010 250]);
add_block('simulink/Sinks/To Workspace', [mdl '/state'], 'Position', [880 20 940 50], 'VariableName', 'state', 'SaveFormat', 'Timeseries');
add_block('simulink/Sinks/To Workspace', [mdl '/channels'], 'Position', [880 230 940 260], 'VariableName', 'channels', 'SaveFormat', 'Timeseries');
add_block('simulink/Sinks/To Workspace', [mdl '/laps'], 'Position', [1080 320 1140 350], 'VariableName', 'laps', 'SaveFormat', 'Timeseries');
add_block('simulink/Sources/Digital Clock', [mdl '/Clock'], 'Position', [780 330 820 360], 'SampleTime', '1/600');

% code of the MATLAB Function blocks
setCode([mdl '/Driver (AI)'], {
    'function u = driver(y, HL)'
    '% AI driver (hotlap.aiDriver): curvature feed-forward, heading and cross-track correction, speed plan.'
    '% y = [x y h vx vy r s lat dLim delta] from the vehicle; u = [steer thr brk].'
    'c = struct(''x'', y(1), ''y'', y(2), ''h'', y(3), ''vx'', y(4), ''vy'', y(5), ''s'', y(7), ''lat'', y(8), ''dLim'', max(y(9), 0.05));'
    'inp = hotlap.aiDriver(c, HL.T, HL.P.vPlan);'
    'u = [inp.steer; inp.thr; inp.brk];'});
setCode([mdl '/Vehicle dynamics'], {
    'function [y, ch] = vehicle(u, HL)'
    '% Single-track model (hotlap.physicsStep) at 600 Hz, lap position every 4 steps as in the game.'
    '% y = [x y h vx vy r s lat dLim delta]; ch = [Fdown Fdrag ax ay P beta grip_g].'
    'persistent c k'
    'if isempty(c), c = HL.c0; k = 0; end'
    'inp = hotlap.driverInput(u(1), u(2), u(3), false, false, false, HL.arcade);'
    '[c, f] = hotlap.physicsStep(c, inp, HL.C, HL.P, HL.dt);'
    'k = k + 1;'
    'if mod(k, 4) == 0'
    '    nr = hotlap.nearestPoint(HL.T, c.x, c.y); c.s = nr.s; c.lat = nr.lat;'
    '    a = HL.T.APRON; c.grass = ~(c.x > a(1) && c.x < a(3) && c.y > a(2) && c.y < a(4));'
    'end'
    'y = [c.x; c.y; c.h; c.vx; c.vy; c.r; c.s; c.lat; c.dLim; c.delta];'
    'ch = [f.Fdown; f.Fdrag; f.ax; f.ay; f.P; f.beta; (f.capF + f.capR) / (HL.C.m * 9.81)];'});
setCode([mdl '/Lap timing'], {
    'function lap = laptiming(s, t, HL)'
    '% Lap counter at the start/finish line (s wraps from the lap length to 0); lap = [count last lap time].'
    'persistent prev t0 n last'
    'if isempty(prev), prev = s; t0 = -1; n = 0; last = 0; end'
    'L = HL.T.LEN; d = s - prev;'
    'if d < -L / 2'
    '    d = d + L; tc = t - (s / max(d, 1e-6)) * (4 / 600);'
    '    if t0 >= 0, n = n + 1; last = tc - t0; end'
    '    t0 = tc;'
    'end'
    'prev = s;'
    'lap = [n; last];'});
for b = {'Driver (AI)', 'Vehicle dynamics', 'Lap timing'}
    ch = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', [mdl '/' b{1}]);
    d = find(ch, '-isa', 'Stateflow.Data', 'Name', 'HL'); d.Scope = 'Parameter'; d.Tunable = false;
end

% wiring
add_line(mdl, 'State feedback/1', 'RT in/1', 'autorouting', 'smart');
add_line(mdl, 'RT in/1', 'Driver (AI)/1');
add_line(mdl, 'Driver (AI)/1', 'RT out/1');
add_line(mdl, 'RT out/1', 'Vehicle dynamics/1');
add_line(mdl, 'Vehicle dynamics/1', 'State feedback/1', 'autorouting', 'smart');
add_line(mdl, 'Vehicle dynamics/1', 'Demux/1');
add_line(mdl, 'Vehicle dynamics/1', 'state/1', 'autorouting', 'smart');
add_line(mdl, 'Vehicle dynamics/2', 'channels/1', 'autorouting', 'smart');
add_line(mdl, 'Vehicle dynamics/2', 'Forces/1', 'autorouting', 'smart');
add_line(mdl, 'Demux/1', 'Driven line/1'); add_line(mdl, 'Demux/2', 'Driven line/2', 'autorouting', 'smart');
add_line(mdl, 'Demux/4', 'To km per h/1', 'autorouting', 'smart'); add_line(mdl, 'To km per h/1', 'Speed km_h/1');
add_line(mdl, 'Demux/7', 'Lap timing/1', 'autorouting', 'smart'); add_line(mdl, 'Clock/1', 'Lap timing/2', 'autorouting', 'smart');
add_line(mdl, 'Lap timing/1', 'laps/1');
for k = [3 5 6 8 9 10], add_block('simulink/Sinks/Terminator', sprintf('%s/T%d', mdl, k), 'Position', [840 40 + 15 * k 850 50 + 15 * k], 'ShowName', 'off'); add_line(mdl, sprintf('Demux/%d', k), sprintf('T%d/1', k)); end
set_param([mdl '/Driven line'], 'xmin', '-10', 'xmax', '320', 'ymin', '0', 'ymax', '200');
ph = get_param([mdl '/Vehicle dynamics'], 'PortHandles'); set(ph.Outport(1), 'DataLogging', 'on', 'Name', 'y');
set(get_param(ph.Outport(2), 'Line'), 'Name', 'ch');

% notes on the canvas
note = Simulink.Annotation([mdl '/HoMo-LAP']);
note.Text = sprintf(['HoMo-LAP · FAUmax tau on the FSG endurance track\n' ...
    'Parameters: HL in the model workspace (homolapModelParams). Run run_simulink_lap(vals) for any setup.\n' ...
    'Driver and vehicle call hotlap.aiDriver and hotlap.physicsStep, the same code as the MATLAB game.']);
note.Position = [260 400 900 460];

% default parameters: stock tau, LTS aero package
mw = get_param(mdl, 'ModelWorkspace'); assignin(mw, 'HL', homolapModelParams());
save_system(mdl, f);
fprintf('wrote %s\n', f);
end

function setCode(blk, lines)
ch = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', blk);
ch.Script = strjoin(lines, newline);
end
